/**
 * Lightweight inline SVG icon system.
 *
 * Each icon is a server-safe React component that renders an inline `<svg>`.
 * No external icon library is imported — the full set is ~2 KB and ships as
 * part of the component tree without an extra network request.
 *
 * Every icon defaults to `aria-hidden="true"` because it is always paired with
 * a visible text label (section 35).
 */

